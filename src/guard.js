// ============================================================
// guard.js — 盾持ち(せなか)
//
// きずな(線)を捨てて、ここに置き換えた。
//
// 線は「2人いると勝手に敵が切れる」仕組みだった。強くはあったが、
// **何もしなくても効いていた。** 力を得る代わりに何かを失っていないので、
// 遊んでいる側からは「ずるい」としか見えない。人数が増えるほど線が増えて、
// ますます楽になっていた —— 「4人だからこそ」の逆をやっていた。
//
// **力の代わりに自由を差し出す形にする。**
//
//   盾持ちは、近い人から順に盾を向ける。盾は「人数-1枚」ある。
//   だから、いつでも **一番遠い ひとりだけ** が背中を撃てる。
//
//   前に出た人は撃てない。撃てないが、盾を引きつけている。
//   引きつけているあいだ、後ろの誰かが背中を撃つ。
//   誰かが動けば距離の順が変わり、役がそのまま入れ替わる。
//
// これは1人では**絶対に**成立しない —— ひとりなら自分が一番近いので、
// 盾は必ず自分を向く。線のように「居るだけで効く」のではなく、
// 立ち位置を毎秒選び直すことでしか成立しない。
//
// 人数で意味が変わる:
//   2人 = 囮と狙撃。前に出るか、下がるかの二択。役がはっきりしている
//   3人 = 盾2枚。真ん中の距離の人も塞がれる。誰が最遠かが読みにくい
//   4人 = 盾3枚。役が高速で回る。持ち場を決めないと全員が塞がれる
// ============================================================

export const GUARD = {
  /** 盾の最大枚数。4人でも3枚まで(必ずひとりは撃てる側に残す)。 */
  MAX_SHIELDS: 3,
  /** 盾持ちは硬い。すぐ溶けると役が一度も入れ替わらないまま終わる。 */
  HP_MUL: 3.0,
  /** 背中に当てた時の倍率。回り込んだ(下がった)ことへの見返り。 */
  BACK_MUL: 2.2,
  /** 盾持ちは遅い。速いと距離の順が事故で決まり、選ぶ余地が消える。 */
  SPEED_MUL: 0.7,
  /** 盾持ちは「一番近い人」を撃つ。囮に代償が無いと、誰も前に出ない。 */
  SHOOT_RATE: 0.5,
};

/**
 * 盾の枚数。生きている人数より1枚少ない。
 *
 * **必ず1人ぶん余らせる**のが要点。全員を塞ぐと詰みになり、
 * 塞ぎ足りないと「近いのに撃てる人」が出て役が曖昧になる。
 *
 * @param alive 生きている人数
 */
export function shieldCount(alive) {
  const n = (alive | 0) - 1;
  return n < 0 ? 0 : n > GUARD.MAX_SHIELDS ? GUARD.MAX_SHIELDS : n;
}

/**
 * いま盾に塞がれている人の id。
 *
 * 角度ではなく**距離の順位**で決める。角度で決めると、敵が画面の上に
 * いるあいだは全員がほぼ同じ方向に見えるので(みんな下にいるから)、
 * 1枚の盾が全員を塞いでしまい「何をしても効かない」時間ができる。
 * 順位なら、どんな距離でも必ずちょうど1人が撃てる側に残る。
 *
 * @param ex,ey   敵の位置
 * @param players [{id,x,y}] 生きている人だけ。id は端末をまたいで一致すること
 * @returns Set<id>
 */
export function blockedIds(ex, ey, players) {
  const out = new Set();
  if (!players || players.length < 2) return out;   // ひとりなら盾は立たない
  const k = shieldCount(players.length);
  if (k <= 0) return out;
  const sorted = players
    .map(p => ({ id: p.id, d: (p.x - ex) * (p.x - ex) + (p.y - ey) * (p.y - ey) }))
    // 距離が同じ時は id で決める。**端末ごとに答えが割れないようにする** ——
    //   割れると「自分は撃てるつもりなのにホストが弾く」が起きる。
    .sort((a, b) => a.d - b.d || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  for (let i = 0; i < k && i < sorted.length; i++) out.add(sorted[i].id);
  return out;
}

/**
 * 盾を1フレーム更新して、敵に貼り付ける。描画も判定もここが正。
 * ホストでもゲストでも同じ結果になる(位置さえ揃っていれば)。
 */
export function updateGuards(enemies, players) {
  for (const e of enemies) {
    if (!e.guard || e.delay > 0) continue;
    e.blocked = blockedIds(e.x, e.y, players);
  }
}

/**
 * この人の弾が通るか。
 * 盾持ちでなければ誰でも通る。盾持ちなら、塞がれていない人だけ。
 */
export function canHit(e, id) {
  if (!e || !e.guard) return true;
  return !(e.blocked && e.blocked.has(id));
}
