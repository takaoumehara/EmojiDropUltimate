// ============================================================
// version.js — このビルドが「どの版か」を1か所で持つ
//
// なぜ要るのか:
//   2人までしか遊べない版と、4人が同時に遊べる版が同時に世に出る。
//   遊ぶ人が「自分が触っているのはどっちか」を言えないと、
//   「4人で入れない」という報告が、どちらの話なのか判別できない。
//   タイトルに小さく出し、共闘ロビーの定員表示もここから引く。
//
// 版の履歴は docs/versions.md。ここは番号だけを持ち、説明は持たない。
// ============================================================

/** 表示用の版番号。docs/versions.md と git tag と必ず揃える。 */
export const VERSION = '2.0.0';

/** 版の呼び名。1.0 は DUO(ふたり)、2.0 は PARTY(最大4人)。 */
export const CODENAME = 'PARTY';
export const CODENAME_JA = 'パーティ';

/** タイトル画面に出す1行。 */
export function versionLabel(ja) {
  return `v${VERSION} ${ja ? CODENAME_JA : CODENAME}`;
}
